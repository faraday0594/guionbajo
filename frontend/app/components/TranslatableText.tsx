function lookupSmartLocal(rawWord: string): string | null {
  const w = rawWord.trim().toLowerCase();
  if (!w) return null;

  if (CONTRACTIONS[w]) return CONTRACTIONS[w];
  if (BASE_DICT[w]) return BASE_DICT[w];

  // Possessive 's
  if (w.endsWith("'s") && w.length > 2) {
    const stem = w.slice(0, -2);
    const hit = lookupSmartLocal(stem);
    if (hit) return `de ${hit.split(' / ')[0]}`;
  }

  // Plurals / 3rd person singular
  if (w.endsWith('ies') && w.length > 4) {
    const cand = w.slice(0, -3) + 'y';
    if (BASE_DICT[cand]) return BASE_DICT[cand];
  }
  if (w.endsWith('ves') && w.length > 4) {
    for (const cand of [w.slice(0, -3) + 'f', w.slice(0, -3) + 'fe']) {
      if (BASE_DICT[cand]) return BASE_DICT[cand];
    }
  }
  if (w.endsWith('es') && w.length > 3) {
    for (const cand of [w.slice(0, -2), w.slice(0, -1)]) {
      if (BASE_DICT[cand]) return BASE_DICT[cand];
    }
  }
  if (w.endsWith('s') && !w.endsWith('ss') && w.length > 2) {
    const cand = w.slice(0, -1);
    if (BASE_DICT[cand]) return BASE_DICT[cand];
  }

  // Past / participle -ed
  if (w.endsWith('ied') && w.length > 4) {
    const cand = w.slice(0, -3) + 'y';
    if (BASE_DICT[cand]) return `${BASE_DICT[cand].split(' / ')[0]} (pasado)`;
  }
  if (w.endsWith('ed') && w.length > 3) {
    const stem2 = w.slice(0, -2);
    const stem1 = w.slice(0, -1);
    // Doubled consonant (stopped -> stop, planned -> plan)
    const stemDouble =
      stem2.length >= 3 && stem2[stem2.length - 1] === stem2[stem2.length - 2]
        ? stem2.slice(0, -1)
        : '';
    for (const cand of [stem2, stem1, stemDouble]) {
      if (cand && BASE_DICT[cand]) {
        return `${BASE_DICT[cand].split(' / ')[0]} (pasado/part.)`;
      }
    }
  }

  // Gerund -ing
  if (w.endsWith('ying') && w.length > 5) {
    const cand = w.slice(0, -4) + 'ie';
    if (BASE_DICT[cand]) return `${BASE_DICT[cand].split(' / ')[0]} (-ando/-iendo)`;
  }
  if (w.endsWith('ing') && w.length > 4) {
    const stem = w.slice(0, -3);
    const stemE = stem + 'e';
    const stemDouble =
      stem.length >= 3 && stem[stem.length - 1] === stem[stem.length - 2]
        ? stem.slice(0, -1)
        : '';
    for (const cand of [stem, stemE, stemDouble]) {
      if (cand && BASE_DICT[cand]) {
        return `${BASE_DICT[cand].split(' / ')[0]} (-ando/-iendo)`;
      }
    }
  }

  // Adverbs -ily / -ly
  if (w.endsWith('ily') && w.length > 4) {
    const cand = w.slice(0, -3) + 'y';
    if (BASE_DICT[cand]) return `${BASE_DICT[cand].split(' / ')[0]} (-mente)`;
  }
  if (w.endsWith('ly') && w.length > 3) {
    for (const cand of [w.slice(0, -2), w.slice(0, -2) + 'e', w.slice(0, -1) + 'e']) {
      if (BASE_DICT[cand]) return `${BASE_DICT[cand].split(' / ')[0]} (-mente)`;
    }
  }

  // Comparatives & Superlatives -ier / -iest / -er / -est
  if (w.endsWith('ier') && w.length > 4) {
    const cand = w.slice(0, -3) + 'y';
    if (BASE_DICT[cand]) return `más ${BASE_DICT[cand].split(' / ')[0]}`;
  }
  if (w.endsWith('iest') && w.length > 5) {
    const cand = w.slice(0, -4) + 'y';
    if (BASE_DICT[cand]) return `el más ${BASE_DICT[cand].split(' / ')[0]}`;
  }
  if (w.endsWith('er') && w.length > 3) {
    const stem = w.slice(0, -2);
    const stemE = w.slice(0, -1);
    const stemDouble =
      stem.length >= 3 && stem[stem.length - 1] === stem[stem.length - 2]
        ? stem.slice(0, -1)
        : '';
    for (const cand of [stem, stemE, stemDouble]) {
      if (cand && BASE_DICT[cand]) return `más ${BASE_DICT[cand].split(' / ')[0]}`;
    }
  }
  if (w.endsWith('est') && w.length > 4) {
    const stem = w.slice(0, -3);
    const stemE = w.slice(0, -2);
    const stemDouble =
      stem.length >= 3 && stem[stem.length - 1] === stem[stem.length - 2]
        ? stem.slice(0, -1)
        : '';
    for (const cand of [stem, stemE, stemDouble]) {
      if (cand && BASE_DICT[cand]) return `el más ${BASE_DICT[cand].split(' / ')[0]}`;
    }
  }

  // Prefijos comunes (un-, re-, dis-, mis-, non-)
  const prefixes: Array<[string, string]> = [
    ['un', 'no / des-'],
    ['dis', 'des- / no '],
    ['re', 'volver a / re-'],
    ['mis', 'mal '],
    ['non', 'no '],
  ];
  for (const [pref, label] of prefixes) {
    if (w.startsWith(pref) && w.length > pref.length + 3) {
      const rest = lookupSmartLocal(w.slice(pref.length));
      if (rest) return `${label}${rest.split(' / ')[0]}`;
    }
  }

  return null;
}

const translationCache = new Map<string, string>();
const inFlightRequests = new Map<string, Promise<string>>();

async function getWordTranslation(word: string, sentence: string): Promise<string> {
  const clean = word.replace(/^[^a-zA-Z']+|[^a-zA-Z']+$/g, '');
  if (!clean) return '';
  const lower = clean.toLowerCase();

  if (translationCache.has(lower)) {
    return translationCache.get(lower)!;
  }

  const localHit = lookupSmartLocal(lower);
  if (localHit) {
    translationCache.set(lower, localHit);
    return localHit;
  }

  if (inFlightRequests.has(lower)) {
    return inFlightRequests.get(lower)!;
  }

  const reqPromise = (async () => {
    // 1. Direct browser query to free MyMemory API (works even if backend is cold/deploying)
    try {
      const url = `https://api.mymemory.translated.net/get?q=${encodeURIComponent(clean)}&langpair=en|es`;
      const r = await fetch(url);
      if (r.ok) {
        const data = await r.json();
        const tr = (data?.responseData?.translatedText || '').trim();
        if (tr) {
          translationCache.set(lower, tr);
          return tr;
        }
      }
    } catch {
      // Fallback to backend
    }

    // 2. Fallback to backend /lesson/translate-word
    try {
      const res = await api.translateWord(clean, sentence);
      const tr = (res?.translation || '').trim();
      if (tr) {
        translationCache.set(lower, tr);
        return tr;
      }
    } catch {
      // Ignore error
    }

    return '';
  })();

  inFlightRequests.set(lower, reqPromise);
  try {
    return await reqPromise;
  } finally {
    inFlightRequests.delete(lower);
  }
}

interface TranslatableTextProps {
  text: string;
  className?: string;
}

export default function TranslatableText({ text, className = '' }: TranslatableTextProps) {
  const [activeIdx, setActiveIdx] = useState<number | null>(null);
  const [translation, setTranslation] = useState<string>('');
  const [loading, setLoading] = useState(false);
  const containerRef = useRef<HTMLSpanElement>(null);
  const activeIdxRef = useRef<number | null>(null);

  useEffect(() => {
    if (activeIdx === null) return;
    const handleOutside = (e: MouseEvent | TouchEvent) => {
      if (containerRef.current && !containerRef.current.contains(e.target as Node)) {
        activeIdxRef.current = null;
        setActiveIdx(null);
      }
    };
    document.addEventListener('mousedown', handleOutside);
    document.addEventListener('touchstart', handleOutside);
    return () => {
      document.removeEventListener('mousedown', handleOutside);
      document.removeEventListener('touchstart', handleOutside);
    };
  }, [activeIdx]);

  if (!text) return null;

  const parts = text.split(/([A-Za-z]+(?:'[A-Za-z]+)?)/g);

  const activateWord = async (idx: number, rawWord: string) => {
    activeIdxRef.current = idx;
    setActiveIdx(idx);

    const lower = rawWord.toLowerCase();
    const cached = translationCache.get(lower) || lookupSmartLocal(lower);
    if (cached) {
      translationCache.set(lower, cached);
      setTranslation(cached);
      setLoading(false);
      return;
    }

    setTranslation('');
    setLoading(true);
    const tr = await getWordTranslation(rawWord, text);
    if (activeIdxRef.current === idx) {
      setTranslation(tr || rawWord);
      setLoading(false);
    }
  };

  return (
    <span ref={containerRef} className={`inline ${className}`}>
      {parts.map((part, idx) => {
        if (!part) return null;
        const isWord = /^[A-Za-z]+(?:'[A-Za-z]+)?$/.test(part);
        if (!isWord) {
          return <React.Fragment key={idx}>{part}</React.Fragment>;
        }

        const isActive = activeIdx === idx;

        return (
          <span
            key={idx}
            className="relative inline-block"
            onMouseEnter={() => activateWord(idx, part)}
            onMouseLeave={() => {
              if (activeIdxRef.current === idx) {
                activeIdxRef.current = null;
                setActiveIdx(null);
              }
            }}
            onClick={(e) => {
              e.stopPropagation();
              if (isActive) {
                activeIdxRef.current = null;
                setActiveIdx(null);
              } else {
                activateWord(idx, part);
              }
            }}
          >
            <span
              className={`border-b border-dotted transition-colors cursor-help rounded-sm px-[1px] ${
                isActive
                  ? 'border-brand-cyan text-brand-cyan bg-brand-cyan/15'
                  : 'border-white/30 hover:border-brand-cyan hover:text-brand-cyan'
              }`}
            >
              {part}
            </span>

            {isActive && (
              <span
                role="tooltip"
                className="pointer-events-none absolute bottom-full left-1/2 -translate-x-1/2 mb-1.5 z-50
                  whitespace-nowrap px-2.5 py-1 rounded-lg bg-slate-950/95 border border-brand-cyan/50
                  text-[11px] font-sans font-semibold text-cyan-200 shadow-xl backdrop-blur-md"
              >
                {loading && !translation ? 'Traduciendo...' : translation}
                <span className="block text-[9px] font-normal text-slate-400 text-center">
                  {part}
                </span>
              </span>
            )}
          </span>
        );
      })}
    </span>
  );
}
