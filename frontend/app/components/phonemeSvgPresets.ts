/**
 * Infer the primary articulatory mouth shape archetype for frontal rendering.
 */
export function inferShapeType(sym: string, tongue_visible?: boolean): MouthShapeType {
  const s = sym.replace(/\//g, '').trim();
  if (tongue_visible || s === 'θ' || s === 'ð') return 'interdental';
  if (['ɔː', 'ɒ', 'ɔɪ', 'əʊ'].includes(s)) return 'rounded_o';
  if (['uː', 'ʊ', 'w', 'ʊə', 'ʃ', 'ʒ', 'tʃ', 'dʒ', 'r'].includes(s)) return 'rounded_tight';
  if (['iː', 'ɪ', 'e', 's', 'z', 'j', 'eɪ', 'ɪə'].includes(s)) return 'spread';
  if (['ɑː', 'æ', 'ʌ', 'aɪ', 'aʊ', 'h'].includes(s)) return 'wide_open';
  if (['p', 'b', 'm'].includes(s)) return 'closed';
  if (['f', 'v'].includes(s)) return 'labiodental';
  return 'neutral';
}

/**
 * Retrieve the SVG parameters for an IPA phoneme symbol, with fallback.
 */
export function getPhonemeSvgParam(ipa: string, customParams?: any): PhonemeSvgParam {
  const cleanIpa = ipa.startsWith("/") ? ipa : `/${ipa}/`;
  const base = PHONEME_SVG_PRESETS[cleanIpa] || PHONEME_SVG_PRESETS["/ə/"];

  const tongue_visible = customParams && customParams.tongue_visible !== undefined
    ? Boolean(customParams.tongue_visible)
    : base.tongue_visible;

  const shape_type: MouthShapeType = (customParams && customParams.shape_type) 
    ? customParams.shape_type 
    : (base.shape_type || inferShapeType(cleanIpa, tongue_visible));

  if (!customParams || typeof customParams !== 'object') {
    return {
      ...base,
      shape_type,
    };
  }

  return {
    ...base,
    lip_w: customParams.lip_w ?? customParams.lip_width ?? base.lip_w,
    lip_drop: customParams.lip_drop ?? base.lip_drop,
    tongue: customParams.tongue_path ?? customParams.tongue ?? base.tongue,
    tex1: customParams.tex1 ?? base.tex1,
    tex2: customParams.tex2 ?? base.tex2,
    focus_x: customParams.focus_x ?? base.focus_x,
    focus_y: customParams.focus_y ?? base.focus_y,
    velum: customParams.velum ?? base.velum,
    uvula_y: customParams.uvula_y ?? base.uvula_y,
    air: customParams.air ?? base.air,
    nasal: customParams.nasal !== undefined ? Boolean(customParams.nasal) : base.nasal,
    tongue_visible,
    voiced: customParams.voiced !== undefined ? Boolean(customParams.voiced) : base.voiced,
    f_desc: customParams.f_desc ?? base.f_desc,
    s_desc: customParams.s_desc ?? base.s_desc,
    lip_lbl: customParams.lip_lbl ?? base.lip_lbl,
    shape_type,
  };
}

